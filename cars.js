  let x = rand() * total;
  let picked = 'common';
  for (const [key, r] of Object.entries(RARITY)) {
    if ((x -= r.weight) < 0) { picked = key; break; }
  }
  const pool = BY_RARITY[picked];
  return pool[Math.floor(rand() * pool.length)];
